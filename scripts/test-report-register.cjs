const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const file = `${process.cwd()}/src/components/reports/ReportTable.tsx`;
const compiled = ts.transpileModule(fs.readFileSync(file,'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.React, esModuleInterop: true } }).outputText;
const component = new Module(file,module);
component.filename=file; component.paths=Module._nodeModulePaths(process.cwd());
const originalRequire = component.require.bind(component);
component.require = name => {
 if(name==='next/navigation')return {usePathname:()=>'/reports/payments'};
 if(name==='@/store')return {useAppStore:selector=>selector({user:{id:'user',businessId:'company'},selectedBusinessId:'company'})};
 if(name==='@/lib/report-export')return {exportToExcel:()=>Promise.resolve()};
 if(name==='@/lib/report-register-export')return {exportRegisterPDF:()=>Promise.resolve()};
 if(name==='@/components/shared/AsyncButton')return {__esModule:true,default:props=>React.createElement('button',null,props.children)};
 return originalRequire(name);
};
component._compile(compiled,file);
const Table=component.exports.default;
const headers=['Voucher','Date','Party','Reference','Account','Mode','Amount','Status'];
const body=Array.from({length:31},(_,i)=>React.createElement('tr',{key:i},...headers.map((h,col)=>React.createElement('td',{key:col},`${h}-row-${i+1}`))));
const html=renderToStaticMarkup(React.createElement(Table,null,React.createElement('thead',null,React.createElement('tr',null,...headers.map(h=>React.createElement('th',{key:h},h)))),React.createElement('tbody',null,...body)));
for(const heading of headers)assert.ok(html.includes(`data-column-label="${heading}"`),`mobile field label missing: ${heading}`);
assert.ok(html.includes('Reference-row-25')); assert.ok(!html.includes('Reference-row-26'));
assert.ok(html.includes('of 31 rows')); assert.ok(html.includes('Excel · 31 rows')); assert.ok(html.includes('PDF · 31 rows'));
assert.ok(html.includes('Search all register rows')); assert.ok(html.includes('Rows per page'));
console.log('PASS register preserves all mobile field labels, renders a bounded page and exports the full filtered count');
const css=fs.readFileSync('src/app/globals.css','utf8');
assert.ok(css.includes('@media screen and (max-width: 767px)'));
assert.ok(css.includes('min-width: 0 !important; width: 100% !important;'));
assert.ok(css.includes('.report-surface .truncate { white-space: normal; overflow: visible;'));
console.log('PASS source mobile rules override resized widths and remove text clipping (visual browser QA remains separate)');
