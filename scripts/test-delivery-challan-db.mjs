import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const company='10000000-0000-4000-8000-000000000001', other='10000000-0000-4000-8000-000000000002';
const owner='20000000-0000-4000-8000-000000000001', outsider='20000000-0000-4000-8000-000000000002', staff='20000000-0000-4000-8000-000000000003';
const bill='30000000-0000-4000-8000-000000000001';
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT NULLIF(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
CREATE TABLE businesses(id uuid PRIMARY KEY);
CREATE TABLE company_members(company_id uuid,user_id uuid,role text,status text);
CREATE TABLE role_permissions(business_id uuid,role text,module text,can_view boolean,can_add boolean,can_export boolean);
CREATE TABLE sale_bills(id uuid PRIMARY KEY,business_id uuid,status text,deleted_at timestamptz,updated_at timestamptz);
CREATE FUNCTION auth_business_id() RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER AS $$ SELECT company_id FROM company_members WHERE user_id=auth.uid() AND status='active' LIMIT 1 $$;
CREATE FUNCTION auth_has_business_access(id uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER AS $$ SELECT EXISTS(SELECT 1 FROM company_members WHERE company_id=id AND user_id=auth.uid() AND status='active') $$;
GRANT USAGE ON SCHEMA public,auth TO authenticated,anon;
INSERT INTO auth.users VALUES ('${owner}'),('${outsider}'),('${staff}');
INSERT INTO businesses VALUES ('${company}'),('${other}');
INSERT INTO company_members VALUES ('${company}','${owner}','owner','active'),('${other}','${outsider}','owner','active'),('${company}','${staff}','staff','active');
INSERT INTO role_permissions VALUES ('${company}','staff','Sales & Billing',true,false,false);
INSERT INTO sale_bills VALUES ('${bill}','${company}','active',null,'2026-10-03');`);
await db.exec(fs.readFileSync('supabase/migrations/20261003000025_sales_delivery_challans.sql','utf8'));
await db.exec(`SELECT set_config('request.jwt.claim.sub','${owner}',false); SET ROLE authenticated;`);
assert.equal((await db.query(`SELECT sales_delivery_challan_permission($1,'can_add') allowed`,[company])).rows[0].allowed,true);
await assert.rejects(db.query(`INSERT INTO sales_delivery_challans(business_id,bill_id,created_by,source_updated_at,document) VALUES ($1,$2,$3,'2026-10-03','{}')`,[company,bill,owner]), /permission denied/);
await db.exec('RESET ROLE');
await assert.rejects(db.query(`INSERT INTO sales_delivery_challans(business_id,bill_id,created_by,document) VALUES ($1,$2,$3,'{}')`,[other,bill,owner]), /same company/);
await assert.rejects(db.query(`INSERT INTO sales_delivery_challans(business_id,bill_id,created_by,source_updated_at,document) VALUES ($1,$2,$3,'2026-10-02','{}')`,[company,bill,owner]), /same company/);
await db.query(`INSERT INTO sales_delivery_challans(business_id,bill_id,created_by,source_updated_at,document) VALUES ($1,$2,$3,'2026-10-03','{}')`,[company,bill,owner]);
await assert.rejects(db.query(`INSERT INTO sales_delivery_challans(business_id,bill_id,created_by,source_updated_at,document) VALUES ($1,$2,$3,'2026-10-03','{}')`,[company,bill,owner]), /unique/);
await db.exec(`SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub','${outsider}',false);`);
assert.equal((await db.query('SELECT * FROM sales_delivery_challans')).rows.length,0);
assert.equal((await db.query(`SELECT sales_delivery_challan_permission($1,'can_add') allowed`,[company])).rows[0].allowed,false);
await db.exec(`SELECT set_config('request.jwt.claim.sub','${staff}',false);`);
assert.equal((await db.query('SELECT * FROM sales_delivery_challans')).rows.length,1);
assert.equal((await db.query(`SELECT sales_delivery_challan_permission($1,'can_add') allowed`,[company])).rows[0].allowed,false);
await assert.rejects(db.query(`UPDATE sales_delivery_challans SET document='{}'`), /permission denied/);
await db.exec('RESET ROLE');
await db.query(`UPDATE company_members SET status='inactive' WHERE user_id=$1`,[staff]);
await db.exec('SET ROLE authenticated');
assert.equal((await db.query('SELECT * FROM sales_delivery_challans')).rows.length,0);
await db.close();
console.log('PASS tenant isolation, trusted membership permissions, immutable snapshots, stale source guard and duplicate prevention');
